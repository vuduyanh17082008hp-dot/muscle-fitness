-- 7. DASHBOARD RPC
-- =========================================================

create or replace function public.get_client_dashboard()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_today date := current_date;

  v_profile jsonb;
  v_targets jsonb;
  v_today_data jsonb;
  v_weight_trend jsonb;
  v_weekly_adherence numeric;
begin
  if v_user_id is null then
    raise exception 'Authentication required'
      using errcode = '42501';
  end if;

  select jsonb_build_object(
    'userId', p.user_id,
    'fullName', p.full_name,
    'avatarUrl', p.avatar_url,
    'timezone', p.timezone,
    'onboardingCompleted', p.onboarding_completed
  )
  into v_profile
  from public.profiles as p
  where p.user_id = v_user_id;

  select jsonb_build_object(
    'goal', fp.goal,
    'currentWeightKg', fp.current_weight_kg,
    'targetWeightKg', fp.target_weight_kg,
    'calories', coalesce(fp.calorie_target, 2000),
    'proteinG', coalesce(fp.protein_target_g, 0),
    'carbsG', coalesce(fp.carb_target_g, 0),
    'fatG', coalesce(fp.fat_target_g, 0),
    'waterMl', coalesce(fp.water_target_ml, 2500),
    'steps', coalesce(fp.step_target, 10000)
  )
  into v_targets
  from public.fitness_profiles as fp
  where fp.user_id = v_user_id;

  select jsonb_build_object(
    'date', dcm.metric_date,

    'caloriesConsumed', dcm.calories_consumed,
    'calorieTarget', dcm.calorie_target,

    'proteinConsumedG', dcm.protein_consumed_g,
    'proteinTargetG', dcm.protein_target_g,

    'waterConsumedMl', dcm.water_consumed_ml,
    'waterTargetMl', dcm.water_target_ml,

    'steps', dcm.steps,
    'stepTarget', dcm.step_target,

    'sleepHours', dcm.sleep_hours,
    'sleepQuality', dcm.sleep_quality,
    'energyLevel', dcm.energy_level,
    'stressLevel', dcm.stress_level,
    'sorenessLevel', dcm.soreness_level,

    'workoutCompleted', dcm.workout_completed,

    'recoveryScore', dcm.recovery_score,
    'adherenceScore', dcm.adherence_score,

    'weightKg', dcm.weight_kg,
    'source', dcm.source
  )
  into v_today_data
  from public.daily_client_metrics as dcm
  where dcm.user_id = v_user_id
    and dcm.metric_date = v_today
  limit 1;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'date', history.measured_on,
        'weightKg', history.weight_kg
      )
      order by history.measured_on
    ),
    '[]'::jsonb
  )
  into v_weight_trend
  from (
    select
      we.measured_on,
      we.weight_kg
    from public.weight_entries as we
    where we.user_id = v_user_id
    order by we.measured_on desc
    limit 14
  ) as history;

  select coalesce(
    round(avg(dcm.adherence_score)::numeric, 1),
    0
  )
  into v_weekly_adherence
  from public.daily_client_metrics as dcm
  where dcm.user_id = v_user_id
    and dcm.metric_date between v_today - 6 and v_today;

  return jsonb_build_object(
    'profile',
    coalesce(v_profile, '{}'::jsonb),

    'targets',
    coalesce(v_targets, '{}'::jsonb),

    'today',
    coalesce(
      v_today_data,
      jsonb_build_object(
        'date', v_today,
        'caloriesConsumed', 0,
        'proteinConsumedG', 0,
        'waterConsumedMl', 0,
        'steps', 0,
        'workoutCompleted', false,
        'recoveryScore', 0,
        'adherenceScore', 0
      )
    ),

    'weightTrend',
    coalesce(v_weight_trend, '[]'::jsonb),

    'weeklyAdherence',
    coalesce(v_weekly_adherence, 0)
  );
end;
$$;

revoke all
on function public.get_client_dashboard()
from public;

grant execute
on function public.get_client_dashboard()
to authenticated;

commit;