set
  water_target_ml = coalesce(water_target_ml, 2500),
  step_target = coalesce(step_target, daily_steps, 10000)
where water_target_ml is null
   or step_target is null;

alter table public.fitness_profiles
  alter column water_target_ml set default 2500,
  alter column step_target set default 10000;

do $$
begin
  if not exists (
    select 1
    from pg_catalog.pg_constraint
    where conname = 'fitness_profiles_water_target_range'
  ) then
    alter table public.fitness_profiles
      add constraint fitness_profiles_water_target_range
      check (
        water_target_ml is null
        or water_target_ml between 250 and 20000
      );
  end if;

  if not exists (
    select 1
    from pg_catalog.pg_constraint
    where conname = 'fitness_profiles_step_target_range'
  ) then
    alter table public.fitness_profiles
      add constraint fitness_profiles_step_target_range
      check (
        step_target is null
        or step_target between 0 and 100000
      );
  end if;
end;
$$;

